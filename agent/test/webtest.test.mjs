function chromiumReady() {
  try {
    const req = createRequire(import.meta.url);
    const pw = req("playwright-core");
    return existsSync(pw.chromium.executablePath()) ? true : `chromium not downloaded (${pw.chromium.executablePath()}) — run: node node_modules/playwright-core/cli.js install chromium`;
  } catch (e) { return `playwright-core not installed: ${e.message}`; }
}
const ready = chromiumReady();
if (ready !== true) console.log(`# skipping webtest browser tests: ${ready}`);

const PAGE = `<!doctype html><html><head><title>Demo App</title></head><body>
<h1>Demo</h1>
<form onsubmit="event.preventDefault()"><label>Name <input id="name" name="name"></label>
<select id="color"><option value="r">Red</option><option value="g">Green</option></select>
<label><input type="checkbox" id="agree"> agree</label></form>
<button id="reveal" onclick="document.getElementById('out').textContent='Hello, '+document.getElementById('name').value+'!'">Reveal</button>
<p id="out"></p>
<a href="/about">About us</a>
</body></html>`;

describe("webtest scenario (chromium)", { skip: ready === true ? false : String(ready) }, () => {
  let server, base;
  before(async () => {
    server = createServer((req, res) => {
      res.setHeader("content-type", "text/html");
      res.end(req.url.startsWith("/about") ? "<!doctype html><title>About</title><h2>About page</h2>" : PAGE);
    });
    await new Promise((r) => server.listen(0, "127.0.0.1", r));
    base = `http://127.0.0.1:${server.address().port}`;
  });
  after(async () => { server.closeAllConnections?.(); await new Promise((r) => server.close(r)); });

  test("passing scenario saves screenshots, video, trace, report and spec", async () => {
    const dir = tmp("scn");
    const r = await W.runScenario({
      dir, name: "Reveal greeting", url: base,
      steps: [
        { action: "goto", url: "/" },
        { action: "fill", selector: "#name", value: "Ann" },
        { action: "select", selector: "#color", value: "Green" },
        { action: "check", selector: "#agree" },
        { action: "click", selector: 'role=button[name="Reveal"]' },
        { action: "expect_text", selector: "#out", text: "Hello, Ann!" },
        { action: "expect_title", text: "Demo" },
        { action: "screenshot", name: "greeting" },
        { action: "click", selector: "text=About us" },
        { action: "expect_url", url: "/about" },
        { action: "expect_visible", selector: "h2" },
      ],
    });
    assert.equal(r.ok, true, r.summary);
    assert.equal(r.steps.length, 11);
    const files = readdirSync(r.outDir);
    const pngs = files.filter((f) => f.endsWith(".png"));
    assert.equal(pngs.length, 11, files.join(","));
    assert.ok(files.includes("step-08-screenshot.png"));
    for (const p of pngs) assert.deepEqual([...readFileSync(join(r.outDir, p)).subarray(0, 8)], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], p);
    assert.ok(r.videoPath?.endsWith(".webm") && existsSync(r.videoPath), "video");
    assert.ok(readFileSync(r.videoPath).length > 1000, "video has content");
    assert.ok(r.tracePath && existsSync(r.tracePath), "trace");
    assert.equal(readFileSync(r.tracePath).subarray(0, 2).toString(), "PK");
    const md = readFileSync(r.reportPath, "utf8");
    assert.match(md, /Result: \*\*PASSED\*\*/);
    assert.match(md, /\| 6 \| expect_text \| #out ∋ "Hello, Ann!" \| pass \|/);
    assert.match(md, /\[step-01-goto\.png\]\(step-01-goto\.png\)/);
    const spec = readFileSync(r.specPath, "utf8");
    assert.ok(r.specPath.endsWith(join("tests", "reveal-greeting.spec.ts")));
    assert.match(spec, /await page\.goto\("\/"\);/);
    assert.match(spec, /toContainText\("Hello, Ann!"\)/);
    assert.match(r.summary, /PASSED — 11\/11 steps/);
    rmSync(dir, { recursive: true, force: true });
  });

  test("failing scenario stops at the failed step and keeps evidence", async () => {
    const dir = tmp("scnfail");
    const { ctx } = fakeCtx(dir);
    const out = await W.webtestTool.handler({
      action: "scenario", name: "missing text", url: base, video: false, step_timeout_ms: 1500,
      steps: [
        { action: "click", selector: "#reveal" },
        { action: "expect_text", text: "This text is not on the page" },
        { action: "click", selector: "#never" },
      ],
    }, ctx);
    assert.equal(out.meta.ok, false);
    assert.match(out.content, /FAILED — 2\/4 steps passed/);
    assert.match(out.content, /Failed at step 3 \(expect_text/);
    assert.match(out.content, /This text is not on the page/);
    const files = readdirSync(out.meta.outDir);
    assert.ok(files.includes("step-03-expect_text-failed.png"), files.join(","));
    assert.ok(!files.some((f) => f.startsWith("step-04")));
    assert.ok(files.includes("trace.zip"));
    assert.ok(!files.some((f) => f.endsWith(".webm")), "video disabled");
    const md = readFileSync(out.meta.report, "utf8");
    assert.match(md, /## Failure/);
    assert.match(md, /!\[failure screenshot\]\(step-03-expect_text-failed\.png\)/);
    // report action picks the newest scenario report
    const rep = await W.webtestTool.handler({ action: "report" }, ctx);
    assert.match(String(rep), /Latest scenario report: .*report\.md/);
    rmSync(dir, { recursive: true, force: true });
  });

  test("egress allowlist blocks navigation", async () => {
    const dir = tmp("egress");
    const r = await W.runScenario({ dir, url: base, steps: [], allowlist: ["example.com"], video: false, trace: false });
    assert.equal(r.ok, false);
    assert.match(r.error, /egress_allowlist/);
    rmSync(dir, { recursive: true, force: true });
  });
});
